import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const shared = await import(
  pathToFileURL(path.join(here, '../packages/shared/dist/index.mjs')).href
);
const { TOOL_SCHEMAS, TOOL_CATEGORIES, CORE_TOOL_NAMES, CRAWL_TOOL_NAMES, TOOL_NAMES } = shared;
const nativeToolNames = new Set(Object.values(TOOL_NAMES.NATIVE));
const nativeTools = TOOL_SCHEMAS.filter((tool) => nativeToolNames.has(tool.name));

const groups = [
  ['navigate', 'Navigation & Tabs'],
  ['perceive', 'Perception & Content Extraction'],
  ['act', 'Interaction & Form Automation'],
  ['observe', 'Observation & Scrolling'],
  ['manage', 'Data & Tab Management'],
  ['workflow', 'Durable Tasks & Verified Skills'],
  ['diagnose', 'Diagnostics & Debugging'],
  ['network', 'Network Interception & Capture'],
];

const sanitizeDesc = (str) => {
  return (str || '').split('\n')[0].replace(/(?<!`)<([a-zA-Z][a-zA-Z0-9_-]*)>(?!`)/g, '`<$1>`');
};

// Serialized UTF-8 JSON bytes; this is not measured Agent token usage.
const footprint = (tools) =>
  (Buffer.byteLength(JSON.stringify(tools), 'utf8') / 1024).toFixed(1) + ' KiB';

const toolDoc = (t) => {
  const props = t.inputSchema?.properties || {};
  const req = t.inputSchema?.required || [];
  const params = Object.entries(props).map(([k, v]) => {
    const en = v.enum ? ':' + v.enum.join('|') : '';
    const rq = req.includes(k) ? ' (required)' : '';
    const desc = sanitizeDesc(v.description);
    return '- `' + k + en + '`' + rq + (desc ? ' — ' + desc : '');
  });
  const desc = sanitizeDesc(t.description);
  return '### `' + t.name + '`\n\n' + desc + '\n\n' + params.join('\n') + '\n';
};

let out = '# BrowserPaw Canonical Tool Reference\n\n';
out +=
  '> Automatically generated by `scripts/gen-tools-doc.mjs` from `packages/shared/src/tools.ts`. To regenerate: `node scripts/gen-tools-doc.mjs`.\n\n';
out += `| Profile | Tool Count | Schema Size (UTF-8 JSON) | Description |\n`;
out += `| :--- | :---: | :---: | :--- |\n`;
out += `| **core** (default) | ${CORE_TOOL_NAMES.size} | ${footprint(TOOL_SCHEMAS.filter((t) => CORE_TOOL_NAMES.has(t.name)))} | Stable nine-tool surface: tasks, skills, navigation, observation, click, fill, discovery |\n`;
out += `| **full** | ${TOOL_SCHEMAS.length} | ${footprint(TOOL_SCHEMAS)} | Complete canonical tool surface: raw CDP access, tab groups, diagnostics, performance |\n`;
out += `| **crawl** | ${CRAWL_TOOL_NAMES.size} | ${footprint(TOOL_SCHEMAS.filter((t) => CRAWL_TOOL_NAMES.has(t.name)))} | High-throughput web extraction, markdown summarization, and media inspection |\n\n`;
out += `Canonical surface: ${TOOL_SCHEMAS.length} tools = ${TOOL_SCHEMAS.length - nativeTools.length} extension-executed tools + ${nativeTools.length} native-server tools (${nativeTools.map((tool) => '`' + tool.name + '`').join(', ')}). Profile counts are Core ${CORE_TOOL_NAMES.size} / Crawl ${CRAWL_TOOL_NAMES.size} / Full ${TOOL_SCHEMAS.length}. Native also renders chrome_tool_docs locally, with an extension compatibility handler. Sizes are serialized UTF-8 JSON bytes, not measured Agent token counts.\n\n`;
out +=
  'Hidden tools remain callable without expanding the list. `chrome_tool_docs` lists categories, inspects `names`, and replaces temporary visible tools with `names` plus `activateForSession:true`; an empty list resets them. Category activation is no longer supported.\n\n';

const byName = new Map(TOOL_SCHEMAS.map((t) => [t.name, t]));
const seen = new Set();
for (const [key, label] of groups) {
  out += '\n## ' + label + '\n\n';
  for (const name of (TOOL_CATEGORIES[key] || '').split(' ').filter(Boolean)) {
    if (seen.has(name)) continue;
    seen.add(name);
    const t = byName.get(name);
    if (t) out += toolDoc(t) + '\n';
  }
}
const remaining = TOOL_SCHEMAS.filter((t) => !seen.has(t.name));
if (remaining.length > 0) {
  out += '\n## Additional Tools\n\n';
  for (const t of remaining) {
    out += toolDoc(t) + '\n';
  }
}
out = out.split('0~~1.0').join('0~1.0').split('0~~1000').join('0~1000');
fs.writeFileSync(path.join(here, '../docs/TOOLS.md'), out.trimEnd() + '\n');
console.log('docs/TOOLS.md regenerated:', TOOL_SCHEMAS.length, 'tools');

const snapshotPath = path.join(here, '../plugins/browserpaw-hermes/core_schemas.json');
const snapshotNames = Object.keys(JSON.parse(fs.readFileSync(snapshotPath, 'utf8')));
const snapshot = Object.fromEntries(
  snapshotNames.map((name) => {
    const tool = byName.get(name);
    if (!tool) throw new Error(`Packaged schema is absent from shared tools: ${name}`);
    return [name, { description: tool.description, inputSchema: tool.inputSchema }];
  }),
);
fs.writeFileSync(snapshotPath, JSON.stringify(snapshot, null, 2) + '\n');
